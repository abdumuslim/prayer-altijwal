import type { AdhkarSlot } from "@/lib/worship-log";

export interface DhikrItem {
  id: string;
  textAr: string;
  /** How many times this dhikr is repeated. */
  repeat: number;
  /** Source note as printed on the poster (hadith grading/collection). */
  source?: string;
}

/** True once every item's tap count has reached its repeat target. */
export function slotComplete(counts: number[], items: DhikrItem[]): boolean {
  return items.every((item, i) => (counts[i] ?? 0) >= item.repeat);
}

/** 0..1 — fraction of the list's items completed (arc moves per dhikr). */
export function listProgress(counts: number[], items: DhikrItem[]): number {
  if (items.length === 0) return 0;
  const done = items.filter((item, i) => (counts[i] ?? 0) >= item.repeat).length;
  return done / items.length;
}

